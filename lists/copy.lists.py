#Python Copy Lists:

"""Use the copy() method"""

#Example: Make a copy of a list with the copy() method.

thislist = ["apple", "banana", "cherry"]
mylist = thislist.copy()
print(mylist)


"""Use the slice Operator"""

#Example: Make a copy of a list with the : operator.

thislist = ["apple", "banana", "cherry"]
mylist = thislist[:]
print(mylist)

